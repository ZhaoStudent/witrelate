class TrapMessage(BaseModel):
    """诱导方的一轮输出。

    ⚠️ 两个字段的可见性**完全不同**：
      · `message` —— 给用户看的那段话（可以带节奏）
      · `traps`   —— **隐藏**的自曝标记，展示层绝不渲染，只在最后揭示时汇总

    让诱导方自己标注用了什么话术，是为了让"揭示"环节有据可依 ——
    否则就得让裁判去猜，而猜错了的揭示会教给用户错误的东西。

    ⚠️ 这里**刻意没有** `round` 字段：轮次号是**服务端的账本**（`pro_rounds + 1`），
    不是诱导方的自述。契约里留着它，就等于给"采纳模型给的轮次"留了条门缝 ——
    旧实现正是这么写的（`int(out.get("round") or nxt)`），于是模型写 `1` 时
    每一轮都被标成"第 1 轮"，写 `"第一轮"` 还会让 `int()` 抛错变成 HTTP 400。
    **记录里的字段绝不外授**：删掉字段，模型就无从提供，也就不可能再被改回去。
    """

    message: str = Field(
        description="这一轮对用户说的话（你在扮演编排他的那个人）。要有说服力，"
        "但不得包含违法内容，也不得写出可定位到现实个人的信息。"
    )
    traps: list[FallacyHit] = Field(
        default_factory=list,
        description="本轮**刻意使用**的误导性话术，逐条诚实自曝；没用就用空列表",
    )


class DeceptionReveal(BaseModel):
    """裁判的收尾揭示 —— 本应用的交付物，也是教学闭环的最后一环。

    ⚠️ 同样**刻意没有** `rounds` 字段：与每轮的 `round` 同源，轮数由服务端
    在 `ExperienceSession.reveal()` 里注入（`pro_rounds`）。裁判只负责
    "话术 / 易带偏点 / 建议 / 复盘"这些**只有它能判断**的内容；
    "本局共交锋几轮"是客观账本，模型很容易只数用户发言、或干脆写 1。

    ⚠️ `hot_spots` 与 `solid_moves` 是**成对**的，缺一不可。只报"你哪里被带偏了"，
    教出来的是**被动**——用户学到"我容易被骗"，而不是"我能顶回去"。
    当事人演练的价值恰恰在于后者：他要的是**下次当场怎么接**。
    """

    event: str = Field(description="本局讨论的事件，一句话")
    traps: list[FallacyHit] = Field(
        default_factory=list, description="全场出现过的误导性话术，按轮次汇总"
    )
    hot_spots: list[str] = Field(
        default_factory=list,
        description="用户最容易被带偏的环节：他接受了哪些没有依据的说法",
    )
    solid_moves: list[str] = Field(
        default_factory=list,
        description="用户**站住了**的地方：哪些反驳真正切中了要害（引用他的原话）。"
        "一条都没有时留空，不要为了凑数而夸他",
    )
    advice: list[str] = Field(
        default_factory=list, description="识别与自保的具体建议，要能落地"
    )
    summary: str = Field(
        description="一段通俗复盘，语气像朋友事后提醒，不要训导、不要居高临下"
    )


class CaseOpening(BaseModel):
    """裁判的**开场立题**结论 —— 对局开始前唯一的把关动作。

    ⚠️ 这个环节此前**只有承诺、没有实现**：模块文档、段标题、
    `JUDGE_INSTRUCTIONS` 里整整一段、连前端 loading 文案都写了它，
    但没有任何代码路径会调用裁判去立题（`_judge` 只在 `reveal()` 里用过一次）。
    也就是说，「命题方向写反了当场指出」这道**唯一的关卡**一直是空的。

    ⚠️ 它与 `opening.inspect_case()` 是**互补**关系，不是替代：

        结构性问题（疑问句 / 价值判断 / 方向倒置 / 清单为空）
            →  `opening.py` 的纯函数判（确定性、可离线穷举）
        语义判断（这道命题值不值得辩、材料够不够）
            →  裁判模型判（只有它能判）

    两边都写进 `SessionState.opening`，前端**分开呈现** ——
    谁判的、判了什么，当事人一眼能看出，出了问题也知道该查哪一边。
    """

    worth_debating: bool = Field(
        description="这道命题值不值得辩：它是不是一个**能有正反两方**的事实争议。"
        "命题根本没法判真假（价值判断 / 没有指向任何具体行为）时为 false"
    )
    sufficiency: Literal["充分", "勉强", "不足"] = Field(
        description="事实清单的充分性，**只能是这三个值之一**"
    )
    gaps: list[str] = Field(
        default_factory=list,
        description="还缺哪些材料；没有就留空。方向写反了也在这里当场指出",
    )
    note: str = Field(
        description="**一句话**交代这一局要辩什么，给当事人看。"
        "不要训导、不要替他喊冤、不要给自保建议（那是收尾揭示的事）"
    )


