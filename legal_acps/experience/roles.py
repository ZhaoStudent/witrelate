"""反诈体验应用 —— 用户作为**被污蔑的当事人**，亲身体验被"带节奏"并当场反击。

═══ 视角：第一人称的当事人演练，不是第三人称的传闻鉴定 ═══

    主链路的视角是「第三人称裁判」：喂进一段**别人的**言论，输出对它的评价。
    本应用的视角反过来，是「第一人称当事人」：

        主链路                          本应用
        ──────────────────────────      ──────────────────────────────────
        别人发的一段话                    「**我**被人这么说了」
        这段话危害几分                    「**我**该怎么反驳才站得住」
        结论给平台 / 公权力机关           结论给**当事人本人**

    这个差别不是文案差别。用户在网上真正会遇到的场景不是"我刷到一条可疑消息"，
    而是"有人在群里 / 评论区这么编排我"。后者他必须当场回应，而且他没有律师。

═══ 与主链路的关系 ═══

    主链路（ACPs 真实互联，6 个已注册 Agent）   体验应用（进程内编排，支持人在回路）
    ────────────────────────────────────────   ──────────────────────────────────────
    legal-consult-leader  受理 / 汇总     ──→   受理官 intake
    fact-judge            立题 / 裁定     ──→   裁判 judge（立题 + 收尾揭示）
    debate-pro            正方（纯辩论）  ──→   诱导方 deceiver（**刻意使用话术**）
    debate-con            反方            ──→   用户本人（扮演反方 = 替自己辩白）

    嵌套形态在体验应用里被完整保留：受理官 → 裁判 → 诱导方，
    用户接替了"反方"的位置，因此链路变成

        用户(反方·当事人) ⟷ 诱导方(正方·指控方) ，由裁判居中组织与揭示

    ⚠️ 判据是"谁的立场"而不是"谁先说话"：命题是**针对用户的指控**
    （例：「他拿了不该拿的东西」），所以正方 = 指控方 = 用户在现实中要面对的那个人，
    反方 = 用户自己。这条方向搞反了，整个体验就从"演练"变成"教人怎么造谣"。

═══ 为什么另起执行体，而不复用已注册的 debate-pro ═══

已注册的 `debate-pro` 的 instructions 是「为被指派的立场构建**尽可能强**的论证」，
它**不会刻意误导**；而反诈体验要的恰恰是「刻意使用误导性话术」。
这是两个互相冲突的目标，所以体验应用另起一个执行体：
不注册到平台、不改动任何已过审的对外契约。

═══ 安全红线（写死在设计里，不要绕过）═══

1. 本应用只用于**教学演示**，不产生任何针对真实个人的指控。
2. **每一局都必须以裁判的"揭示"收尾** —— 不允许在没有揭示的情况下让用户离开。
   少了这一步，这个应用就从"反诈教育"变成了"真的在误导人"。
3. 诱导方只允许使用**话术**（证据层 4 类 + 修辞层 6 类，见 `contracts.FallacyKind`），
   不得教唆违法、不得编造针对具体真人的负面事实。
4. ⚠️ 诱导方**扮演的是"编排用户的那个人"，攻击的是用户在这个虚构局里的
   可信度与人格**（这正是污蔑/断章取义的模拟对象）—— 但边界卡在**论述层面**：
   可以质疑他的动机、放大他的措辞、把不确定说成确定；
   **不可以**编造可指向真实个人的具体负面事实、不可以威胁/人肉/教唆违法、
   不可以把攻击延伸到现实中的第三人。**模拟可以像，但不能变成真的。**
"""

